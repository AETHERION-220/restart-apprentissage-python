# Déclaration des variables
nom = "Jean"
prenom = "David"
username = "david"

# Exemple 1 : concaténation avec l'opérateur +
print(nom + username)
print("Bonjour " + prenom + " " + nom + ", nous sommes ravis de vous voir")

# Exemple 2 : affichage avec des virgules
print("Bonjour", prenom, nom, "nous sommes ravis de vous voir")

# Exemple 3 : f-string, méthode recommandée
print(f"Bonjour {prenom} {nom}, nous sommes ravis de vous voir")