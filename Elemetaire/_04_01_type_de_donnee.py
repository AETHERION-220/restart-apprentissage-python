# Les types de données en Python
# Les variables peuvent contenir différents types de valeurs.

# 1. Entier (int) : nombres sans virgule
age = 20
print(age)
print(type(age))

# 2. Nombre décimal (float) : nombres avec virgule
prix = 12.5
print(prix)
print(type(prix))

# 3. Chaîne de caractères (str) : texte
nom = "Jean"
print(nom)
print(type(nom))

# 4. Booléen (bool) : True ou False
est_adulte = True
print(est_adulte)
print(type(est_adulte))

# 5. Liste (list) : plusieurs valeurs dans une variable
fruits = ["mangue", "pomme", "orange"]
print(fruits)
print(type(fruits))

# Exemple de calcul avec des nombres
nombre_1 = 15
nombre_2 = 5
print(nombre_1 + nombre_2)

# Exemple de concaténation avec du texte
prenom = "David"
print("Bonjour " + prenom)

# Exemple avec plusieurs types dans une même logique
nom = "Marie"
age = 18
est_etudiante = True

print(f"Je m'appelle {nom} et j'ai {age} ans.")
print(est_etudiante)
